package registry

import (
	"fmt"
	"net/http"
	"testing"

	"github.com/stretchr/testify/require"
)

func TestManagementUnknownFields(t *testing.T) {
	t.Parallel()
	for _, tc := range []struct{ path, body, want string }{
		{"/principals", `{"id":"my-id","display_name":"Test"}`, `unknown field "id" (accepted: display_name, namespace, role, status); principal ids are generated by the server; caller-chosen id is not supported`},
		{"/principals", `{"display_nam":"Test"}`, `unknown field "display_nam" (accepted: display_name, namespace, role, status)`},
		{"/bindings", `{"principal":%q,"agent":"atlas","id":"my-id"}`, `unknown field "id" (accepted: principal, agent, as_agent)`},
		{"/grants", `{"principal":%q,"subject":{"type":"agent","ref":"atlas"},"actions":["send"],"id":"my-id"}`, `unknown field "id" (accepted: principal, subject, actions, expires_at, note)`},
		{"/grants", `{"principal":%q,"subject":{"type":"agent","ref":"atlas","surprise":true},"actions":["send"]}`, `subject: unknown field "surprise" (accepted: type, ref)`},
	} {
		t.Run(tc.path+"/"+tc.want, func(t *testing.T) {
			m := newMgmtTest(t)
			mint, p := m.post(t, "/principals", m.token, `{}`)
			require.Equal(t, http.StatusCreated, mint.Code)
			body := tc.body
			if tc.path != "/principals" {
				body = fmt.Sprintf(body, p["id"])
			}
			before := m.appendCount(t)
			rec, out := m.post(t, tc.path, m.token, body)
			require.Equal(t, http.StatusBadRequest, rec.Code, rec.Body.String())
			require.Equal(t, tc.want, out["error"])
			require.Equal(t, before, m.appendCount(t), "refused request must not append a record")
			t.Log(out["error"])
		})
	}
}
